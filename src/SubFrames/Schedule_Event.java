    private void Schedule_Event_BtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Schedule_Event_BtnActionPerformed
        // TODO add your handling code here:
        String code  = Event_Code_TextField.getText();
    String title = Event_Title_TextField.getText();
    String date  = Event_Date_TextField.getText();
    String startText = Start_Hour_TextField.getText();
    String endText   = End_Hour_TextField.getText();
    int maxP = (Integer) Max_Participants_Spinner.getValue();

    if (code.isEmpty() || title.isEmpty() || date.isEmpty() 
        || startText.isEmpty() || endText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }
    
    if (Select_Room_ComboBox.getSelectedItem() == null || Select_Organizer_ComboBox.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select Room and Organizer.");
            return;
        }

    int start = Integer.parseInt(startText);
    int end   = Integer.parseInt(endText);
    
    // ✅ Check start hour is before end hour
    if (start >= end) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Start hour must be before end hour!");
        return;
    }

    Classes.Event newEvent = new Classes.Event(code, title, date, start, end, maxP);

    // ✅ Get selected room and organizer
    int roomIndex = Select_Room_ComboBox.getSelectedIndex();
    int orgIndex  = Select_Organizer_ComboBox.getSelectedIndex();
    
    Classes.Room selectedRoom = null;
    Classes.Organizer selectedOrg = null;
    
    if (!Application_Gui.RoomFrame.Room_List.isEmpty()) {
        selectedRoom = Application_Gui.RoomFrame.Room_List.get(roomIndex);
    }
    if (!Application_Gui.OrganizerFrame.Organizer_List.isEmpty()) {
        selectedOrg = Application_Gui.OrganizerFrame.Organizer_List.get(orgIndex);
    }

    // ✅ Check room and organizer conflicts with existing events
    for (Classes.Event existing : Application_Gui.EventFrame.Event_List) {
        if (newEvent.hasConflict(existing)) {
            
            // Check same room
            if (selectedRoom != null && existing.room != null &&
                existing.room.roomNumber.equals(selectedRoom.roomNumber)) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Room " + selectedRoom.roomNumber + 
                    " is already booked during this time!\n" +
                    "Conflict with: " + existing.title + "\n" +
                    "Please choose a different room or time.");
                return;
            }
            
            // Check same organizer
            if (selectedOrg != null && existing.organizer != null &&
                existing.organizer.name.equals(selectedOrg.name)) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Organizer " + selectedOrg.name + 
                    " is already managing an event during this time!\n" +
                    "Conflict with: " + existing.title + "\n" +
                    "Please choose a different organizer or time.");
                return;
            }
        }
    }

    // ✅ No conflicts — assign room and organizer
    if (selectedRoom != null) {
        newEvent.assignRoom(selectedRoom);
    }
    if (selectedOrg != null) {
        selectedOrg.createEvent(newEvent);
    }
    
    // Equipment assignment
int eqIndex = Select_Equipment_ComboBox.getSelectedIndex();

if (eqIndex > 0) {
    Classes.Equipment selectedEq =
        Application_Gui.EquipmentFrame.Equipment_List.get(eqIndex - 1);

    if (selectedEq.quantityAvailable <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
            selectedEq.name + " is not available!\n" +
            "Quantity is 0.");
        return;
    }

    newEvent.addEquipment(selectedEq, 1);
    selectedEq.quantityAvailable -= 1;
    Application_Gui.EquipmentFrame.loadEquipmentToList();
}


    Application_Gui.EventFrame.Event_List.add(newEvent);
    Application_Gui.EventFrame.loadEventsToTable();
    javax.swing.JOptionPane.showMessageDialog(this, "Event scheduled successfully!");
    this.dispose();
    }//GEN-LAST:event_Schedule_Event_BtnActionPerformed

