    private void Add_Room_BtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Add_Room_BtnActionPerformed
        // TODO add your handling code here:
        String roomNumber = Room_Number_TextField.getText();
    String building   = Building_TextField.getText();
    String capText    = Capacity_TextField.getText();

    if (roomNumber.isEmpty() || building.isEmpty() || capText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }
    
    
    
    int capacity = Integer.parseInt(capText);
    Classes.Room r = new Classes.Room(roomNumber, building, capacity);
    Application_Gui.RoomFrame.Room_List.add(r);
    Application_Gui.RoomFrame.loadRoomsToTable();
    javax.swing.JOptionPane.showMessageDialog(this, "Room added successfully!");
    this.dispose();
    }//GEN-LAST:event_Add_Room_BtnActionPerformed

