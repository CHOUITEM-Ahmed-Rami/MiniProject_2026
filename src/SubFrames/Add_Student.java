    private void Add_Student_BtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Add_Student_BtnActionPerformed
        // TODO add your handling code here:
        String name  = Student_Name_TextField.getText();
    String email = Student_Email_TextField.getText();
    String level = Student_Level_TextField.getText();
    String dept  = Student_Departement_TextField.getText();

    if (name.isEmpty() || email.isEmpty() || level.isEmpty() || dept.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }
    
    if (!email.contains("@") || !email.contains(".")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid email address.", "Invalid Email", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
    
    for (Classes.Student s : Application_Gui.StudentFrame.Students_List) {
            if (s.email.equalsIgnoreCase(email)) {
                javax.swing.JOptionPane.showMessageDialog(this, "A student with this email is already registered.", "Duplicate Student", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

    int id = Application_Gui.StudentFrame.Students_List.size() + 1;
    Classes.Student s = new Classes.Student(id, name, email, level, dept);
    Application_Gui.StudentFrame.Students_List.add(s);
    Application_Gui.StudentFrame.loadStudentsToTable();
    javax.swing.JOptionPane.showMessageDialog(this, "Student added successfully!");
    this.dispose();
    }//GEN-LAST:event_Add_Student_BtnActionPerformed

