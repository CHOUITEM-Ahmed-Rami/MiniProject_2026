    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int selectedRow = Organizer_Display_Table.getSelectedRow();
    
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Please select an organizer first!");
        return;
    }
    
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
        "Are you sure you want to delete this organizer?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        Organizer_List.remove(selectedRow);
        loadOrganizersToTable();
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Organizer deleted successfully!");
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void Search_TextFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_Search_TextFieldKeyReleased
        // TODO add your handling code here:
        String searchText = Search_TextField.getText().toLowerCase();
    
    javax.swing.table.DefaultTableModel model = 
        (javax.swing.table.DefaultTableModel) Organizer_Display_Table.getModel();
    model.setRowCount(0);
    
    for (Classes.Organizer o : Organizer_List) {
        if (o.name.toLowerCase().contains(searchText) ||
            o.email.toLowerCase().contains(searchText) ||
            o.clubName.toLowerCase().contains(searchText)) {
            
            Object[] row = { o.id, o.name, o.email, o.clubName };
            model.addRow(row);
        }
    }
    }//GEN-LAST:event_Search_TextFieldKeyReleased

