    private void Register_BtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Register_BtnActionPerformed
        // TODO add your handling code here:
        int sIndex = Select_Student_ComboBox.getSelectedIndex();
    int eIndex = Select_Event_ComboBox.getSelectedIndex();

    if (Application_Gui.StudentFrame.Students_List.isEmpty() 
        || Application_Gui.EventFrame.Event_List.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Please add students and events first!");
        return;
    }

    Classes.Student s = Application_Gui.StudentFrame.Students_List.get(sIndex);
    Classes.Event   e = Application_Gui.EventFrame.Event_List.get(eIndex);

    // ✅ Check if student already registered in this exact event
    if (s.registeredEvents.contains(e)) {
        javax.swing.JOptionPane.showMessageDialog(this,
            s.name + " is already registered in " + e.title + "!\n" +
            "A student cannot register twice in the same event.");
        return;
    }

    // ✅ Check if event is full
    if (e.isFull()) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Sorry! " + e.title + " is full.\n" +
            "Maximum participants: " + e.maxParticipants);
        return;
    }

    // ✅ Check time conflict with student's other events
    for (Classes.Event registered : s.registeredEvents) {
        if (e.hasConflict(registered)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Schedule conflict for " + s.name + "!\n" +
                "They are already registered in: " + registered.title + "\n" +
                "Date: " + registered.date + 
                " | Time: " + registered.startHour + 
                " - " + registered.endHour + "\n\n" +
                "Please choose a different event or time.");
            return;
        }
    }

    // ✅ All checks passed — register
    int regId = Application_Gui.EquipmentFrame.Registration_List.size() + 1;
    String today = java.time.LocalDate.now().toString();

    Classes.Registration reg = new Classes.Registration(regId, today, "Pending", s, e);
    reg.confirmRegistration();
    Application_Gui.EquipmentFrame.Registration_List.add(reg);

    javax.swing.JOptionPane.showMessageDialog(this, 
        "Registration status: " + reg.status);
    }//GEN-LAST:event_Register_BtnActionPerformed

