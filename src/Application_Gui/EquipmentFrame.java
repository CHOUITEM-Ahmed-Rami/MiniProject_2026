    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int selectedIndex = Equipment_List_Display.getSelectedIndex();
    
    if (selectedIndex == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Please select an equipment first!");
        return;
    }
    
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
        "Are you sure you want to delete this equipment?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        Equipment_List.remove(selectedIndex);
        loadEquipmentToList();
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Equipment deleted successfully!");
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void Search_TextFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_Search_TextFieldKeyReleased
        // TODO add your handling code here:
        String searchText = Search_TextField.getText().toLowerCase();
    
    javax.swing.DefaultListModel<String> model = 
        new javax.swing.DefaultListModel<>();
    
    for (Classes.Equipment e : Equipment_List) {
        if (e.name.toLowerCase().contains(searchText)) {
            model.addElement(e.name + " [Qty: " + e.quantityAvailable + "]");
        }
    }
    Equipment_List_Display.setModel(model);
    }//GEN-LAST:event_Search_TextFieldKeyReleased

