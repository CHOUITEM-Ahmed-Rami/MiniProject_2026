    public static void loadReportTable() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) Report_Display_Table.getModel();
    model.setRowCount(0);

    for (Classes.Registration reg : Application_Gui.EquipmentFrame.Registration_List) {
        Classes.Student s = reg.student;
        Classes.Event   e = reg.event;
        Object[] row = {
            reg.registrationId,
            reg.registrationDate,
            reg.status,
            s.name,
            s.email,
            s.level,
            s.department,
            e.code,
            e.title,
            e.date,
            e.startHour,
            e.endHour,
            e.maxParticipants
        };
        model.addRow(row);
    }
    
}

