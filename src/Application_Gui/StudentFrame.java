    private void Delete_Student_BtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Delete_Student_BtnActionPerformed
        // TODO add your handling code here:
        int selectedRow = Student_Display_Table.getSelectedRow();
    
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Please select a student from the table first!");
        return;
    }
    
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
        "Are you sure you want to delete this student?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        Students_List.remove(selectedRow);
        loadStudentsToTable();
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Student deleted successfully!");
    }
    }//GEN-LAST:event_Delete_Student_BtnActionPerformed

    private void Search_TextFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_Search_TextFieldKeyReleased
        // TODO add your handling code here:
         String searchText = Search_TextField.getText().toLowerCase();
    
    javax.swing.table.DefaultTableModel model = 
        (javax.swing.table.DefaultTableModel) Student_Display_Table.getModel();
    model.setRowCount(0); // clear table
    
    for (Classes.Student s : Students_List) {
        // Search by name or email or level or department
        if (s.name.toLowerCase().contains(searchText) ||
            s.email.toLowerCase().contains(searchText) ||
            s.level.toLowerCase().contains(searchText) ||
            s.department.toLowerCase().contains(searchText)) {
            
            Object[] row = { s.id, s.name, s.email, s.level, s.department };
            model.addRow(row);
        }
    }
    }//GEN-LAST:event_Search_TextFieldKeyReleased

